const salary = 100000
switch (salary) {
    case 10000:
        console.log("Poor man");
        break;
    case 100000:
        console.log("Rich man");
        break;
    case 1000000:
        console.log("Millionare");
        break;
    case 10000000:
        console.log("Billionare");
        break;
    default:
        console.log("I don't know salary.");
        break;
}